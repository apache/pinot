/// Real generated bytes and the production native table manager used by the authenticated quorum execution test.
final class NativeInstallationScenario implements AutoCloseable {
  private final Path _directory;
  private final ExecutorService _executor = Executors.newSingleThreadExecutor();
  private final Content _content;
  private OfflineTableDataManager _manager;

  NativeInstallationScenario(Path directory, UUID tableId, UUID segmentId, TableConfig table, Schema schema)
      throws Exception {
    _directory = directory;
    Path generated = Files.createDirectories(directory.resolve("generated"));
    String name = "orders_segment";
    SegmentGeneratorConfig config = new SegmentGeneratorConfig(table, schema);
    config.setOutDir(generated.toString());
    config.setSegmentName(name);
    List<GenericRow> rows = new ArrayList<>();
    for (int i : List.of(2, 0, 4, 1, 3)) {
      GenericRow row = new GenericRow();
      row.putValue("id", i);
      rows.add(row);
    }
    SegmentIndexCreationDriverImpl driver = new SegmentIndexCreationDriverImpl();
    driver.init(config, new GenericRowRecordReader(rows));
    driver.build();
    Path segment = generated.resolve(name);
    Path archive = directory.resolve("immutable.tar.gz");
    TarCompressionUtils.createCompressedTarFile(segment.toFile(), archive.toFile());
    String digest = HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(Files.readAllBytes(archive)));
    long crc = new SegmentMetadataImpl(segment.toFile()).getCrc();
    _content = new Content(table.getTableName(), tableId, name, segmentId, digest, archive.toUri().toString(),
        new LoaderDescriptor(crc, 0, false, null, null, 100, 200, Map.of()));
    SegmentFetcherFactory.init(new PinotConfiguration());
  }

  Content content() {
    return _content;
  }

  void start(Work work)
      throws Exception {
    if (_manager != null) {
      _manager.shutDown();
    }
    TableDataManagerMetadata.SegmentSnapshot capture = RatisOfflineSegmentExecutor.snapshot(work);
    TableDataManagerMetadata metadata = new TableDataManagerMetadata() {
      @Override
      public TableSnapshot fetchTable(String tableNameWithType) {
        return new TableSnapshot(capture.tableConfig(), capture.schema());
      }

      @Override
      public SegmentSnapshot fetchSegment(String tableNameWithType, String segmentName) {
        throw new IllegalStateException("This scenario loads only through explicit native actions");
      }
    };
    InstanceDataManagerConfig config = mock(InstanceDataManagerConfig.class);
    when(config.getInstanceId()).thenReturn(work.target().server().participantId());
    when(config.getInstanceDataDir()).thenReturn(_directory.resolve("server").toString());
    when(config.getSegmentDirectoryLoader()).thenReturn(
        SegmentDirectoryLoaderRegistry.DEFAULT_SEGMENT_DIRECTORY_LOADER_NAME);
    when(config.shouldCheckCRCOnSegmentLoad()).thenReturn(true);
    _manager = new OfflineTableDataManager();
    _manager.initWithMetadata(config, metadata, new SegmentLocks(), _content.tableName(), new SegmentReloadSemaphore(1),
        _executor, null, null, null, false, mock(ServerReloadJobStatusCache.class));
    _manager.start();
  }

  Executor installer() {
    return _manager.nativeExecutor();
  }

  void verifyRows(boolean invertedIndex)
      throws IOException {
    verifyRows(_manager, invertedIndex);
  }

  void verifyRows(TableDataManager manager, boolean invertedIndex)
      throws IOException {
    SegmentDataManager acquired = manager.acquireSegment(_content.segmentName());
    assertNotNull(acquired);
    try {
      assertEquals(acquired.getSegment().getSegmentMetadata().getTotalDocs(), 5);
      DataSource source = acquired.getSegment().getDataSource("id");
      assertNotNull(source.getDictionary());
      int sum = 0;
      try (PinotSegmentColumnReader reader = new PinotSegmentColumnReader(acquired.getSegment(), "id")) {
        for (int row = 0; row < 5; row++) {
          sum += (Integer) reader.getValue(row);
        }
      }
      assertEquals(sum, 10);
      assertEquals(source.getInvertedIndex() != null, invertedIndex);
    } finally {
      manager.releaseSegment(acquired);
    }
  }

  @Override
  public void close() {
    if (_manager != null) {
      _manager.shutDown();
    }
    _executor.shutdownNow();
  }
}
