package org.apache.pinot.coordination.ratis.transport;

import java.io.IOException;
import org.apache.pinot.coordination.ratis.metadata.MembershipProtocol.ParticipantToken;
import org.apache.pinot.coordination.ratis.metadata.MetadataProtocol.GetInstallationWork;
import org.apache.pinot.coordination.ratis.metadata.OfflineInstallationProtocol.InstallationSnapshot;
import org.apache.pinot.coordination.ratis.metadata.OfflineInstallationProtocol.WorkResult;


/// Coherent linearizable work and metadata projection for one authenticated server. Implementations validate
/// the exact live session at capture and return no other server's targets or receipts. Snapshot capture permits
/// pre-ready hydration; physical installation work continues to require readiness.
public interface InstallationAccess {
  WorkResult query(GetInstallationWork query, long timeoutMillis) throws IOException;

  InstallationSnapshot installationSnapshot(ParticipantToken server, int maxRecords, int maxBytes, long timeoutMillis)
      throws IOException;
}
